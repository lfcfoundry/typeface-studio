// Build-time: compress the research tables into src/core/mood-data.js (shipped in the app).
// usage: node tools/build-mood-data.mjs <research/prototype/mood folder>
import fs from 'node:fs';
const dir = process.argv[2];
const read = f => JSON.parse(fs.readFileSync(`${dir}/${f}`));
const G = read('google-fonts-shapes-and-tags.json'), GL = read('glove-table-40k.json');
const { LEXICON } = await import(`${dir}/lexicon-with-business.mjs`); const { STOP } = await import(`${dir}/anchors.mjs`);
const tags = GL.tags, tagIdx = new Map(tags.map((t, i) => [t, i]));
const metrics = G.metrics;
// word -> [[tagIdx, weight*100]...]
const lex = {};
for (const [w, o] of Object.entries(LEXICON)) lex[w] = Object.entries(o).filter(([t]) => tagIdx.has(t)).map(([t, v]) => [tagIdx.get(t), Math.round(v * 100)]);
// fonts: rows "tag:weight/10,...|z*10,..." (tag weights and shifts rounded to one decimal digit)
const fontRows = [...G.train, ...G.test].map(f => Object.entries(f.tags).filter(([t]) => tagIdx.has(t)).map(([t, v]) => `${tagIdx.get(t)}:${Math.round(v / 10)}`).join(',') + '|' + f.z.map(v => v == null ? '' : Math.round(v * 10)).join(','));
// glove: words sorted and front-coded; entries as bytes (count, then tag, weight pairs) in base64
const ws = Object.keys(GL.table).sort(); let wtxt = '', prev = '', bytes = [];
for (const w of ws) { let p = 0; while (p < prev.length && p < w.length && prev[p] === w[p]) p++; wtxt += String.fromCharCode(48 + Math.min(p, 40)) + w.slice(p) + ' '; prev = w; const e = GL.table[w]; bytes.push(e.length); for (const [t, sc] of e) bytes.push(t, sc); }
const glove = { words: wtxt, data: Buffer.from(bytes).toString('base64') };
const out = { tags, metrics, stop: [...STOP], lex, glove, thr: GL.threshold, fonts: fontRows.join(';') };
// Pack with deflate (the browser unpacks it natively with DecompressionStream, so no decoder ships).
import zlib from 'node:zlib';
const packed = zlib.deflateRawSync(Buffer.from(JSON.stringify(out)), { level: 9 }).toString('base64');
fs.writeFileSync(new URL('../src/core/mood-data.js', import.meta.url), `// Generated by tools/build-mood-data.mjs from measured open-license font shapes. Do not edit.\n// Raw deflate of JSON, base64. Unpacked in the browser with DecompressionStream.\nexport default '${packed}';\n`);
console.log('fonts', fontRows.length, 'lex', Object.keys(lex).length, 'glove', ws.length, 'packed chars', packed.length);
