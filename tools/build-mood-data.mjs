// Build-time: compress the research tables into src/core/mood-data.js (shipped in the app).
// usage: node tools/build-mood-data.mjs <research/prototype/mood folder>
import fs from 'node:fs';
const dir = process.argv[2];
const read = f => JSON.parse(fs.readFileSync(`${dir}/${f}`));
const G = read('google-fonts-shapes-and-tags.json'), GL = read('glove-table-40k.json');
const { LEXICON } = await import(`${dir}/lexicon.mjs`); const { STOP } = await import(`${dir}/anchors.mjs`);
const tags = GL.tags, tagIdx = new Map(tags.map((t, i) => [t, i]));
const metrics = G.metrics;
// word -> [[tagIdx, weight*100]...]
const lex = {};
for (const [w, o] of Object.entries(LEXICON)) lex[w] = Object.entries(o).filter(([t]) => tagIdx.has(t)).map(([t, v]) => [tagIdx.get(t), Math.round(v * 100)]);
// fonts: tag weights as [idx, val] pairs, z as ints*100
const fonts = [...G.train, ...G.test].map(f => [Object.entries(f.tags).filter(([t]) => tagIdx.has(t)).map(([t, v]) => [tagIdx.get(t), Math.round(v)]), f.z.map(v => v == null ? null : Math.round(v * 100))]);
// Compact rows into strings to keep the file small
const fontRows = fonts.map(([t, z]) => t.map(([i, v]) => `${i}:${v}`).join(',') + '|' + z.map(v => v ?? '').join(','));
const out = { tags, metrics, stop: [...STOP], lex, glove: GL.table, thr: GL.threshold, fonts: fontRows };
fs.writeFileSync(new URL('../src/core/mood-data.js', import.meta.url), `// Generated by tools/build-mood-data.mjs from measured open-license font shapes. Do not edit.\nexport default ${JSON.stringify(out)};\n`);
console.log('fonts', fontRows.length, 'lex', Object.keys(lex).length, 'glove', Object.keys(GL.table).length);
